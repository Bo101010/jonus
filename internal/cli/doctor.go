// checkStatus is the outcome of a single diagnostic check. It starts at 1 so
// that the zero value is never a valid result.
type checkStatus int

const (
	statusOK checkStatus = iota + 1
	statusWarn
	statusFail
)

func (s checkStatus) String() string {
	switch s {
	case statusOK:
		return "ok"
	case statusWarn:
		return "warn"
	case statusFail:
		return "FAIL"
	default:
		return "?"
	}
}

// check is one line of the doctor report.
type check struct {
	name   string
	status checkStatus
	detail string
}

func newDoctorCmd() *cobra.Command {
	var strict bool

	cmd := &cobra.Command{
		Use:   "doctor",
		Short: "Check that this machine can run jonus",
		Long: `Doctor inspects the local environment and reports what is ready and what
is missing.

Only what the configured engine needs is checked. The mock engine needs
nothing installed, and the cloud engine needs a key and a reachable gateway
rather than a Python interpreter or a downloaded model.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			cfg, err := resolveConfig(cmd)
			if err != nil {
				return err
			}

			results := runChecks(cmd.Context(), cfg)
			if err := renderChecks(cmd, results); err != nil {
				return err
			}

			if strict {
				for _, c := range results {
					if c.status == statusFail {
						return fmt.Errorf("%s failed", c.name)
					}
				}
			}
			return nil
		},
	}

	cmd.Flags().BoolVar(&strict, "strict", false, "exit non-zero if any check fails")
	return cmd
}

// runChecks probes the environment. Order is deliberate: the checks that block
// everything else come first.
//
// What is checked depends on the configured engine. Reporting a missing Python
// interpreter to someone whose songs are generated by a hosted API would be
// noise dressed up as diagnostics.
func runChecks(ctx context.Context, cfg config.Config) []check {
	checks := []check{
		checkGo(),
		checkDataDir(cfg.DataDir),
		checkEngine(cfg),
	}

	switch cfg.EngineName {
	case config.EngineCloud:
		checks = append(checks, checkCloud(ctx, cfg.Cloud)...)

	case config.EngineACEStep:
		checks = append(checks,
			checkCommand("uv", "package manager for the Python sidecar"),
			checkPython(),
			checkHFMirror(ctx),
			checkPort("sidecar port", cfg.Sidecar.BaseURL),
		)
	}

	return append(checks,
		checkCommand("ffmpeg", "audio transcoding and decoding"),
		checkPort("http port", cfg.HTTPAddr),
	)
}

// checkEngine reports which engine is configured and what it needs.
func checkEngine(cfg config.Config) check {
	switch cfg.EngineName {
	case config.EngineMock:
		return check{
			name:   "engine",
			status: statusOK,
			detail: "mock — synthesises audio locally and needs nothing installed",
		}

	case config.EngineCloud:
		gateway := cfg.Cloud.BaseURL
		if gateway == "" {
			gateway = cloud.DefaultBaseURL
		}
		return check{
			name:   "engine",
			status: statusOK,
			detail: fmt.Sprintf("cloud — %s via %s", providerLabel(cfg.Cloud.Provider), gateway),
		}

	case config.EngineACEStep:
		return check{name: "engine", status: statusOK, detail: "ace-step — a local model, driven over HTTP"}

	default:
		return check{name: "engine", status: statusWarn, detail: cfg.EngineName}
	}
}

// providerLabel names the vendor, defaulting to the one the engine would pick.
func providerLabel(name string) string {
	if name == "" {
		return cloud.ProviderMiniMax + " (default)"
	}
	return name
}

// checkCloud verifies the hosted engine is configured and that the gateway is
// actually reachable from this network.
func checkCloud(ctx context.Context, cfg config.Cloud) []check {
	key := check{
		name:   "cloud api key",
		status: statusOK,
		detail: "set",
	}
	// The key itself is never printed, only whether there is one.
	if strings.TrimSpace(cfg.APIKey) == "" {
		key = check{
			name:   "cloud api key",
			status: statusFail,
			detail: "JONUS_CLOUD_API_KEY is not set — the cloud engine cannot start without it",
		}
	}

	gateway := cfg.BaseURL
	if gateway == "" {
		gateway = cloud.DefaultBaseURL
	}

	return []check{key, checkReachable(ctx, "cloud gateway", gateway)}
}

// checkReachable reports whether a host answers at all. An HTTP error status
// still proves the network path works, which is the only thing under test.
func checkReachable(ctx context.Context, label, base string) check {
	ctx, cancel := context.WithTimeout(ctx, 8*time.Second)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, http.MethodGet, base, nil)
	if err != nil {
		return check{name: label, status: statusWarn, detail: err.Error()}
	}

	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return check{
			name:   label,
			status: statusWarn,
			detail: fmt.Sprintf("%s is unreachable — generation will fail", base),
		}
	}
	defer resp.Body.Close()

	return check{
		name:   label,
		status: statusOK,
		detail: fmt.Sprintf("%s reachable (HTTP %d)", base, resp.StatusCode),
	}
}

func checkGo() check {
	v := strings.TrimPrefix(runtime.Version(), "go")
	return check{
		name:   "go toolchain",
		status: statusOK,
		detail: fmt.Sprintf("built with go%s (%s/%s)", v, runtime.GOOS, runtime.GOARCH),
	}
}

func checkDataDir(dir string) check {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return check{name: "data directory", status: statusFail, detail: err.Error()}
	}
	probe := filepath.Join(dir, ".write-probe")
	if err := os.WriteFile(probe, []byte("ok"), 0o600); err != nil {
		return check{name: "data directory", status: statusFail, detail: err.Error()}
	}
	if err := os.Remove(probe); err != nil {
		return check{name: "data directory", status: statusWarn, detail: "writable, but probe could not be removed"}
	}
	return check{name: "data directory", status: statusOK, detail: dir}
}

func checkCommand(name, purpose string) check {
	path, err := exec.LookPath(name)
	if err != nil {
		return check{
			name:   name,
			status: statusWarn,
			detail: fmt.Sprintf("not found — needed for %s (brew install %s)", purpose, name),
		}
	}
	return check{name: name, status: statusOK, detail: path}
}

// checkPython looks for an interpreter the ML sidecar can actually run on.
// Every target model requires 3.12 or older; the system Python is often newer,
// so a pinned interpreter is checked for by name.
func checkPython() check {
	for _, candidate := range []string{"python3.12", "python3.11"} {
		if path, err := exec.LookPath(candidate); err == nil {
			return check{name: "python (sidecar)", status: statusOK, detail: path}
		}
	}
	return check{
		name:   "python (sidecar)",
		status: statusWarn,
		detail: "no python3.12 or python3.11 on PATH — the ACE-Step engine needs one (brew install python@3.12)",
	}
}

// checkHFMirror verifies the model download endpoint is reachable. The public
// huggingface.co is unreachable from some networks, so the mirror is what
// matters in practice.
func checkHFMirror(ctx context.Context) check {
	ctx, cancel := context.WithTimeout(ctx, 8*time.Second)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, http.MethodHead, "https://hf-mirror.com", nil)
	if err != nil {
		return check{name: "hf mirror", status: statusWarn, detail: err.Error()}
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return check{name: "hf mirror", status: statusWarn, detail: "hf-mirror.com unreachable — model download will fail"}
	}
	defer resp.Body.Close()

	return check{
		name:   "hf mirror",
		status: statusOK,
		detail: fmt.Sprintf("hf-mirror.com reachable (HTTP %d); set HF_ENDPOINT when downloading weights", resp.StatusCode),
	}
}

// checkPort reports whether the host:port in addr can be bound. A URL such as
// "http://127.0.0.1:8001" is accepted alongside a bare "host:port".
func checkPort(label, addr string) check {
	hostport := addr
	if i := strings.Index(hostport, "://"); i >= 0 {
		hostport = hostport[i+3:]
	}
	if !strings.Contains(hostport, ":") {
		return check{name: label, status: statusWarn, detail: fmt.Sprintf("cannot parse address %q", addr)}
	}

	ln, err := net.Listen("tcp", hostport)
	if err != nil {
		return check{name: label, status: statusWarn, detail: fmt.Sprintf("%s is already in use", hostport)}
	}
	if err := ln.Close(); err != nil {
		return check{name: label, status: statusWarn, detail: err.Error()}
	}
	return check{name: label, status: statusOK, detail: fmt.Sprintf("%s is free", hostport)}
}

func renderChecks(cmd *cobra.Command, results []check) error {
	out := cmd.OutOrStdout()
	w := tabwriter.NewWriter(out, 0, 0, 2, ' ', 0)

	var failures, warnings int
	for _, c := range results {
		switch c.status {
		case statusFail:
			failures++
		case statusWarn:
			warnings++
		}
		fmt.Fprintf(w, "%s\t%s\t%s\n", c.status, c.name, c.detail)
	}
	if err := w.Flush(); err != nil {
		return err
	}

	fmt.Fprintln(out)
	switch {
	case failures > 0:
		fmt.Fprintf(out, "%d failed, %d warning(s)\n", failures, warnings)
	case warnings > 0:
		fmt.Fprintf(out, "ready, with %d warning(s)\n", warnings)
	default:
		fmt.Fprintln(out, "all checks passed")
	}
	return nil
}
